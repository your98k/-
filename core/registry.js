  var SUBJECTS = {};

  function build(subject, def) {
    if (!SUBJECTS[subject]) {
      SUBJECTS[subject] = { id: subject, name: def.name, short: def.short, color: def.color, stages: {} };
    }
    var target = SUBJECTS[subject];
    Object.keys(def.stages).forEach(function (stageName) {
      var rows = def.stages[stageName];
      var kpList = [], kpMap = {}, chapters = {}, grades = {};
      rows.forEach(function (r) {
        var kp = {
          id: r[0], name: r[1], grade: r[2], term: r[3],
          chapter: r[4], chapterName: r[5], gen: r[6] !== false
        };
        if (!kpMap[kp.id]) { kpMap[kp.id] = kp; kpList.push(kp); }
        else { kpMap[kp.id].gen = kpMap[kp.id].gen && kp.gen; }
        if (!chapters[kp.chapter]) {
          chapters[kp.chapter] = { id: kp.chapter, name: kp.chapterName, grade: kp.grade, term: kp.term, kps: [] };
        }
        if (chapters[kp.chapter].kps.indexOf(kp.id) < 0) chapters[kp.chapter].kps.push(kp.id);
        var gk = 'g' + kp.grade;
        grades[gk] = grades[gk] || { up: [], down: [] };
        var bucket = kp.term === 1 ? grades[gk].up : grades[gk].down;
        if (bucket.indexOf(kp.id) < 0) bucket.push(kp.id);
      });
      target.stages[stageName] = {
        name: stageName === 'primary' ? '小学' : stageName === 'junior' ? '初中' : '高中',
        grades: grades,
        chapters: chapters,
        kps: kpList,
        kpMap: kpMap
      };
    });
  }

